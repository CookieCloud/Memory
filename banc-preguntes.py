TEMES = ['natura', 'mon', 'historia', 'llengua']
NIVELLS = ['fàcil', 'mitjà', 'difícil']


def comprova(llista=None):
    problemes, vistes = [], set()
    for i, (p, b, o, e, t, n) in enumerate(llista if llista is not None else BANC):
        if p in vistes: problemes.append(f'{i}: pregunta repetida — {p}')
        vistes.add(p)
        if len(o) != 3: problemes.append(f'{i}: {len(o)} respostes dolentes — {p}')
        if b in o: problemes.append(f'{i}: la bona també és a les dolentes — {p}')
        if len(set(o)) != 3: problemes.append(f'{i}: dolentes repetides — {p}')
        if len(e) < 60: problemes.append(f'{i}: explicació massa curta — {p}')
        if t not in TEMES: problemes.append(f'{i}: tema desconegut {t}')
        if n not in (0, 1, 2): problemes.append(f'{i}: nivell desconegut {n}')
        if not p.endswith('?'): problemes.append(f'{i}: no acaba amb interrogant — {p}')
    return problemes


# Llargades mesurades al navegador en un telèfon de 360x640, que és el més
# petit que es fa servir avui. El que compta no és cada camp per separat
# sinó el conjunt: les quatre respostes s'apilen l'una sobre l'altra, i
# cadascuna que passa d'una línia empeny la següent fora de la pantalla.
MAX_PREGUNTA = 100        # més enllà, la caixa de la pregunta ocupa massa
RESPOSTA_UNA_LINIA = 40   # fins aquí, una resposta cap en una sola línia
RESPOSTA_MAXIMA = 80      # i això només si la resta són curtes
MAX_EXPLICACIO = 220      # més llarga, s'ha de desplaçar per llegir-la


def avisos(llista=None):
    """Coses que no trenquen res però que es veuran estretes al telèfon"""
    fora = []
    for i, (p, b, o, e, t, n) in enumerate(llista if llista is not None else BANC):
        if len(p) > MAX_PREGUNTA:
            fora.append(f'{i}: pregunta de {len(p)} lletres (el màxim còmode és {MAX_PREGUNTA}) — {p[:55]}…')

        respostes = [b] + list(o)
        llargues = [r for r in respostes if len(r) > RESPOSTA_UNA_LINIA]
        if len(llargues) > 1:
            fora.append(f'{i}: {len(llargues)} respostes de més de {RESPOSTA_UNA_LINIA} lletres '
                        f'(només n\'hi hauria d\'haver una de llarga) — {p[:45]}…')
        for r in respostes:
            if len(r) > RESPOSTA_MAXIMA:
                fora.append(f'{i}: resposta de {len(r)} lletres (el màxim és {RESPOSTA_MAXIMA}) — {r[:45]}…')

        if len(e) > MAX_EXPLICACIO:
            fora.append(f'{i}: explicació de {len(e)} lletres (el màxim còmode és {MAX_EXPLICACIO}) — {p[:45]}…')
    return fora


def js():
    """El banc amb el format que feia servir l'index.html (ja no cal)"""
    def txt(x): return "'" + x.replace('\\', '\\\\').replace("'", "\\'") + "'"
    files = []
    for p, b, o, e, t, n in BANC:
        files.append('  {p:%s, b:%s, o:[%s], e:%s, t:%s, n:%d}'
                     % (txt(p), txt(b), ', '.join(txt(x) for x in o), txt(e), txt(t), n))
    return 'const BANC_PREGUNTES = [\n' + ',\n'.join(files) + '\n];\n'


def comes_que_falten(cami):
    """El lector de JSON només ensenya el primer error. Aquesta funció
       troba d'un cop totes les línies que acaben en } sense la coma."""
    with open(cami, encoding='utf-8') as f:
        linies = f.read().split('\n')
    fora = []
    for i in range(len(linies) - 1):
        ara, seg = linies[i].rstrip(), linies[i+1].lstrip()
        if ara.endswith('}') and not ara.endswith('},') and seg.startswith('{'):
            fora.append(i + 1)
    return fora


def arreglar(cami):
    """Posa les comes que falten i treu les preguntes repetides"""
    with open(cami, encoding='utf-8') as f:
        text = f.read()
    linies = text.split('\n')
    comes = comes_que_falten(cami)
    for n in comes:
        linies[n-1] = linies[n-1].rstrip() + ','
    text = '\n'.join(linies)

    try:
        dades = json.loads(text)
    except json.JSONDecodeError as e:
        print('Encara queda un error de format que no sé arreglar sol:')
        print('  %s (línia %d, columna %d)' % (e.msg, e.lineno, e.colno))
        if comes:
            print('  (hi he posat %d comes que faltaven, però en queda un altre)' % len(comes))
        return False

    llista = dades if isinstance(dades, list) else dades.get('preguntes', [])
    vistes, netes, repes = set(), [], []
    for q in llista:
        clau = q.get('p', '')
        if clau in vistes: repes.append(clau); continue
        vistes.add(clau); netes.append(q)

    ajuda = dades.get('_com_afegir_preguntes', '') if isinstance(dades, dict) else ''
    files = [json.dumps(q, ensure_ascii=False) for q in netes]
    sortida = '{\n'
    if ajuda: sortida += '  "_com_afegir_preguntes": ' + json.dumps(ajuda, ensure_ascii=False) + ',\n'
    sortida += '  "preguntes": [\n    ' + ',\n    '.join(files) + '\n  ]\n}\n'

    with open(cami + '.abans', 'w', encoding='utf-8') as f:
        f.write(text if not comes else open(cami, encoding='utf-8').read())
    with open(cami, 'w', encoding='utf-8') as f:
        f.write(sortida)

    print('Arreglat:')
    if comes: print('  · %d comes afegides (línies %s)' % (len(comes), ', '.join(map(str, comes))))
    if repes:
        print('  · %d preguntes repetides tretes:' % len(repes))
        for r in repes[:8]: print('        %s' % r[:70])
        if len(repes) > 8: print('        … i %d més' % (len(repes) - 8))
    if not comes and not repes: print('  · no hi havia res a arreglar')
    print('  · queden %d preguntes' % len(netes))
    print('  (La còpia d\'abans ha quedat a %s.abans)' % cami)
    return True


def preguntes_del_json(cami):
    """Llegeix el preguntes.json i el torna com a llista de tuples"""
    with open(cami, encoding='utf-8') as f:
        dades = json.load(f)
    llista = dades if isinstance(dades, list) else dades.get('preguntes', [])
    return [(q.get('p', ''), q.get('b', ''), q.get('o', []),
             q.get('e', ''), q.get('t', ''), q.get('n', -1)) for q in llista]


def json_del_banc():
    """Escriu la llista BANC amb el format del preguntes.json"""
    ajuda = ("Cada línia de la llista preguntes és una pregunta. "
             "p = la pregunta · b = la resposta bona · o = les tres respostes dolentes · "
             "e = l'explicació que surt després de respondre · "
             "t = el tema (natura, mon, historia, llengua) · "
             "n = el nivell (0 fàcil, 1 mitjà, 2 difícil). "
             "Per afegir-ne una, copia una línia sencera, enganxa-la a sota i canvia-la; "
             "totes han d'acabar amb coma menys l'última. "
             "Si dins del text hi ha d'anar una cometa doble, s'escriu \\\" . "
             "Per posar una paraula en cursiva, envolta-la d'asteriscs.")
    files = [json.dumps({"p": p, "b": b, "o": list(o), "e": e, "t": t, "n": n},
                        ensure_ascii=False)
             for p, b, o, e, t, n in BANC]
    return ('{\n  "_com_afegir_preguntes": ' + json.dumps(ajuda, ensure_ascii=False) + ',\n'
            '  "preguntes": [\n    ' + ',\n    '.join(files) + '\n  ]\n}\n')


